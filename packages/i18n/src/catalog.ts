import { extra } from "./extra";
import { safeLanguage } from "./locale";
export type TranslationKey = BaseKey | keyof typeof extra;
export const catalogs = { fr: frBase, en: enBase, sw: swBase, ln: lnBase };
export function translate(
  language: Language,
  key: TranslationKey,
  params: Record<string, string | number> = {},
) {
  const l = safeLanguage(language);
  const e = extra[key as keyof typeof extra];
  const value = e
    ? e[({ fr: 0, en: 1, sw: 2, ln: 3 } as const)[l]]
    : catalogs[l][key as BaseKey];
  return value.replace(/\{(\w+)\}/g, (match, key) =>
    params[key] === undefined ? match : String(params[key]),
  );
}
