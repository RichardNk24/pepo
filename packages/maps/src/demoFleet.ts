export function demoFleet(center: Point): DemoVehicle[] {
  const inLubumbashi =
    Math.hypot(center.latitude + 11.664, (center.longitude - 27.479) * 0.98) <
    0.18;
  if (inLubumbashi)
    return Array.from({ length: 6 }, (_, i) => {
      const road = ROAD_LOOPS[i % ROAD_LOOPS.length];
      const path = road.points.map(([latitude, longitude]) => ({
        latitude,
        longitude,
      }));
      return {
        id: `demo-lubumbashi-${i}`,
        kind: i % 2 === 0 ? "moto" : "taxi",
        ...path[0],
        path,
        phase: [0.12, 0.28, 0.48, 0.65, 0.72, 0.85][i],
        speed: i % 2 === 0 ? 3.8 : 3.0,
      };
    });
  return [
    [0.0013, 0.0006],
    [-0.0011, 0.0018],
    [0.0004, -0.0016],
    [-0.0018, -0.0007],
    [0.0024, -0.002],
    [-0.0003, 0.003],
  ].map(([lat, lon], i) => ({
    id: `demo-vehicle-${i}`,
    kind: i % 2 === 0 ? "moto" : "taxi",
    latitude: center.latitude + lat,
    longitude: center.longitude + lon,
  }));
}
