export function createFleetMotion(vehicles: DemoVehicle[]) {
  const rad = (n: number) => (n * Math.PI) / 180;
  const prepared = vehicles.map((vehicle) => {
    const points =
      vehicle.path && vehicle.path.length > 1 ? vehicle.path : [vehicle];
    const lengths = points.slice(1).map((p, i) => {
      const a = points[i];
      const x =
        rad(p.longitude - a.longitude) *
        Math.cos(rad((p.latitude + a.latitude) / 2));
      const y = rad(p.latitude - a.latitude);
      return Math.hypot(x, y) * 6371000;
    });
    return {
      vehicle,
      points,
      lengths,
      total: lengths.reduce((a, b) => a + b, 0),
    };
  });
  return {
    frame(seconds: number) {
      return prepared.map(({ vehicle, points, lengths, total }) => {
        if (!total) return { ...vehicle, heading: 0 };
        let remaining =
          ((vehicle.phase || 0) * total + seconds * (vehicle.speed || 3.2)) %
          total;
        let segment = 0;
        while (segment < lengths.length - 1 && remaining > lengths[segment])
          remaining -= lengths[segment++];
        const a = points[segment],
          b = points[segment + 1];
        const t = lengths[segment] ? remaining / lengths[segment] : 0;
        const dx =
          (b.longitude - a.longitude) *
          Math.cos(rad((a.latitude + b.latitude) / 2));
        const dy = b.latitude - a.latitude;
        return {
          id: vehicle.id,
          kind: vehicle.kind,
          latitude: a.latitude + (b.latitude - a.latitude) * t,
          longitude: a.longitude + (b.longitude - a.longitude) * t,
          heading: ((Math.atan2(dx, dy) * 180) / Math.PI + 360) % 360,
        };
      });
    },
  };
}
