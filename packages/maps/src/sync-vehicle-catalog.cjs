const fs = require("node:fs");
const path = require("node:path");
function syncCatalog() {
  const root = path.resolve(__dirname);
  const folder = path.join(root, "assets/vehicles/catalog");
  const names = {
    moto: ["moto.png"],
    motoSend: ["moto-send.png", "moto.png"],
    taxi: ["taxi.png"],
    suv: ["suv.png"],
    minibus: ["minibus.png"],
    tricycle: ["tricycle.png"],
    truck: ["camion.png"],
    pickupTruck: ["pick-up truck.png", "pickup.png"],
  };
  const files = fs.existsSync(folder) ? fs.readdirSync(folder) : [];
  const entries = Object.entries(names).flatMap(([kind, aliases]) => {
    const filename = aliases
      .map((n) => files.find((f) => f.toLowerCase() === n))
      .find(Boolean);
    return filename
      ? [
          `  ${kind}: require(${JSON.stringify("../assets/vehicles/catalog/" + filename)}),`,
        ]
      : [];
  });
  const output = `// Generated by scripts/sync-vehicle-catalog.cjs. Add your PNGs and restart Metro.\nimport type {ImageSourcePropType} from "react-native";\nimport type {ActiveVehicleKind} from "@pepo/types/model";\nexport const VEHICLE_IMAGES: Partial<Record<ActiveVehicleKind, ImageSourcePropType>> = {\n${entries.join("\n")}\n};\n`;
  const target = path.join(root, "src/vehicleCatalog.generated.ts");
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output)
    fs.writeFileSync(target, output);

  // Map markers need true top-down artwork. Prefer those dedicated assets,
  // while falling back to the existing catalogue art until a top view is added.
  const mapNames = {
    moto: ["moto-top.png", "catalog/moto.png"],
    motoSend: ["moto-send.png", "moto-send-top.png", "moto-top.png", "catalog/moto.png"],
    taxi: ["car-top.png", "car-topo.png", "taxi-top.png", "catalog/taxi.png"],
    suv: ["suv-top.png", "catalog/suv.png"],
    minibus: ["minibus-top.png", "minibus.png", "catalog/minibus.png"],
    tricycle: ["petita-top.png", "tricycle-top.png", "catalog/tricycle.png"],
    truck: ["camion-top.png", "truck-top.png", "catalog/camion.png"],
    pickupTruck: ["pickup-truck-top.png", "pickup-truc-top.png", "pickup-top.png", "catalog/pick-up truck.png", "catalog/pickup.png"],
  };
  const vehicleRoot = path.join(root, "assets/vehicles");
  const mapEntries = Object.entries(mapNames).flatMap(([kind, candidates]) => {
    const relative = candidates.find((candidate) =>
      fs.existsSync(path.join(vehicleRoot, candidate)),
    );
    return relative
      ? [`  ${kind}: require(${JSON.stringify("../assets/vehicles/" + relative)}),`]
      : [];
  });
  const mapOutput = `// Generated by scripts/sync-vehicle-catalog.cjs.\nimport type {ImageSourcePropType} from "react-native";\nimport type {ActiveVehicleKind} from "@pepo/types/model";\nexport const MAP_VEHICLE_IMAGES: Partial<Record<ActiveVehicleKind, ImageSourcePropType>> = {\n${mapEntries.join("\n")}\n};\n`;
  const mapTarget = path.join(root, "src/mapVehicleCatalog.generated.ts");
  if (!fs.existsSync(mapTarget) || fs.readFileSync(mapTarget, "utf8") !== mapOutput)
    fs.writeFileSync(mapTarget, mapOutput);
}
module.exports = syncCatalog;
if (require.main === module) syncCatalog();
