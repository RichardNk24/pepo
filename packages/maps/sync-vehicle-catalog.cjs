const fs = require("node:fs");
const path = require("node:path");
function syncCatalog() {
  const root = path.resolve(__dirname);
  const folder = path.join(root, "assets/vehicles/catalog");
  const names = {
    moto: ["moto.png"],
    motoSend: ["moto-send.png", "moto.png"],
    taxi: ["taxi.png"],
    suv: ["suv.png"],
    minibus: ["minibus.png"],
    tricycle: ["tricycle.png"],
    truck: ["camion.png"],
    pickupTruck: ["pick-up truck.png", "pickup.png"],
  };
  const files = fs.existsSync(folder) ? fs.readdirSync(folder) : [];
  const entries = Object.entries(names).flatMap(([kind, aliases]) => {
    const filename = aliases
      .map((n) => files.find((f) => f.toLowerCase() === n))
      .find(Boolean);
    return filename
      ? [
          `  ${kind}: require(${JSON.stringify("../assets/vehicles/catalog/" + filename)}),`,
        ]
      : [];
  });
  const output = `// Generated by scripts/sync-vehicle-catalog.cjs. Add your PNGs and restart Metro.\nimport type {ImageSourcePropType} from "react-native";\nimport type {ActiveVehicleKind} from "@pepo/types/model";\nexport const VEHICLE_IMAGES: Partial<Record<ActiveVehicleKind, ImageSourcePropType>> = {\n${entries.join("\n")}\n};\n`;
  const target = path.join(root, "src/vehicleCatalog.generated.ts");
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== output)
    fs.writeFileSync(target, output);
}
module.exports = syncCatalog;
if (require.main === module) syncCatalog();
